/* Add the bar list to the storefront menu and emit the matching D1 migration.
 *
 * Data lives in _work/drinks-data.json (transcribed from the printed drinks
 * menu). Running this script is a one-time operation: it appends the three
 * drinks categories to assets/js/menu.js and writes migrations/0003_drinks.sql.
 *
 * Usage: node _work/apply_drinks.mjs
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "assets", "js", "menu.js");
const DATA = path.join(ROOT, "_work", "drinks-data.json");
const MIGRATION = path.join(ROOT, "migrations", "0003_drinks.sql");
const VERSION = "2";

const drinks = JSON.parse(fs.readFileSync(DATA, "utf8"));

function loadMenu() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(SOURCE, "utf8"), sandbox, { filename: "menu.js" });
  return sandbox.window.MISO_MENU;
}

function q(value) {
  return JSON.stringify(String(value));
}

function jsPrice(value) {
  if (value === null || value === undefined) return "null";
  if (!Number.isInteger(value) || value < 0) throw new Error("Bad price: " + value);
  return String(value);
}

function categoryBlock(cat) {
  const lines = [];
  lines.push("  {");
  lines.push("    id: " + q(cat.id) + ",");
  lines.push("    name: " + q(cat.name) + ",");
  lines.push("    kicker: " + q(cat.kicker || "") + ",");
  lines.push("    blurb: " + q(cat.blurb || "") + ",");
  lines.push("    image: " + (cat.image ? q(cat.image) : "null") + ",");
  lines.push("    groups: [");
  cat.groups.forEach((group, gi) => {
    lines.push("      {");
    lines.push("        name: " + q(group.name) + ",");
    lines.push("        items: [");
    group.items.forEach((item, ii) => {
      lines.push("          {");
      lines.push("            id: " + q(item.id) + ",");
      lines.push("            name: " + q(item.name) + ",");
      lines.push("            desc: " + q(item.desc || "") + ",");
      lines.push("            price: " + jsPrice(item.price) + ",");
      lines.push("            tags: " + JSON.stringify(item.tags || []));
      lines.push("          }" + (ii < group.items.length - 1 ? "," : ""));
    });
    lines.push("        ]");
    lines.push("      }" + (gi < cat.groups.length - 1 ? "," : ""));
  });
  lines.push("    ]");
  lines.push("  }");
  return lines.join("\n");
}

/* ------------------------------------------------------------ validate -- */

const menu = loadMenu();
const existingCategories = new Set(menu.map((cat) => cat.id));
const existingItems = new Set();
for (const cat of menu) {
  for (const group of cat.groups) {
    for (const item of group.items) existingItems.add(item.id);
  }
}

for (const cat of drinks) {
  if (existingCategories.has(cat.id)) {
    throw new Error("Category already in menu.js: " + cat.id);
  }
  if (!Array.isArray(cat.groups) || !cat.groups.length) {
    throw new Error("Category has no groups: " + cat.id);
  }
  const groupNames = new Set();
  for (const group of cat.groups) {
    if (groupNames.has(group.name)) throw new Error("Duplicate group " + group.name);
    groupNames.add(group.name);
    if (!group.items.length) throw new Error("Empty group: " + group.name);
    for (const item of group.items) {
      if (existingItems.has(item.id)) throw new Error("Duplicate item id: " + item.id);
      existingItems.add(item.id);
    }
  }
  existingCategories.add(cat.id);
}

/* ------------------------------------------------------- append to menu -- */

const marker = "\n];\n\nwindow.MISO_SIGNATURES";
let text = fs.readFileSync(SOURCE, "utf8");
const at = text.lastIndexOf(marker);
if (at === -1) throw new Error("Could not find the end of MISO_MENU in menu.js");

const addition = ",\n" + drinks.map(categoryBlock).join(",\n");
text = text.slice(0, at) + addition + text.slice(at);
fs.writeFileSync(SOURCE, text, "utf8");

/* ------------------------------------------------------------- migration -- */

function sqlStr(value) {
  if (value === null || value === undefined) return "NULL";
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function slug(value) {
  return String(value)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const fullMenu = loadMenu();
const lines = [];
lines.push("-- MISO drinks list (migration 0003).");
lines.push("-- Generated by _work/apply_drinks.mjs from _work/drinks-data.json.");
lines.push("-- Additive only: the food menu in 0002 stays untouched.");
lines.push("");
lines.push(
  "INSERT OR IGNORE INTO meta (key, value) VALUES ('menu_version', " + sqlStr(VERSION) + ");"
);
lines.push(
  "UPDATE meta SET value = " + sqlStr(VERSION) + " WHERE key = 'menu_version' AND value <> " + sqlStr(VERSION) + ";"
);
lines.push("");

for (const cat of drinks) {
  const sortOrder = fullMenu.findIndex((row) => row.id === cat.id);
  lines.push(
    "INSERT OR IGNORE INTO categories (id, name, kicker, blurb, image, sort_order, hidden) VALUES (" +
      [
        sqlStr(cat.id),
        sqlStr(cat.name),
        sqlStr(cat.kicker || ""),
        sqlStr(cat.blurb || ""),
        sqlStr(cat.image),
        sortOrder,
        0
      ].join(", ") +
      ");"
  );
}

for (const cat of drinks) {
  for (const [gi, group] of cat.groups.entries()) {
    const id = cat.id + "/" + slug(group.name);
    lines.push("");
    lines.push(
      "INSERT OR IGNORE INTO menu_groups (id, category_id, name, sort_order) VALUES (" +
        [sqlStr(id), sqlStr(cat.id), sqlStr(group.name), gi].join(", ") +
        ");"
    );
    for (const [ii, item] of group.items.entries()) {
      lines.push(
        "INSERT OR IGNORE INTO items (id, group_id, name, description, price, tags, sort_order, hidden) VALUES (" +
          [
            sqlStr(item.id),
            sqlStr(id),
            sqlStr(item.name),
            sqlStr(item.desc || ""),
            item.price === null || item.price === undefined ? "NULL" : Number(item.price),
            sqlStr(JSON.stringify(item.tags || [])),
            ii,
            0
          ].join(", ") +
          ");"
      );
    }
  }
}

lines.push("");
fs.writeFileSync(MIGRATION, lines.join("\n"), "utf8");

const addedItems = drinks.reduce(
  (n, cat) => n + cat.groups.reduce((m, group) => m + group.items.length, 0),
  0
);
console.log(
  "Appended " +
    drinks.length +
    " categories / " +
    addedItems +
    " items to menu.js; wrote " +
    path.relative(ROOT, MIGRATION)
);
