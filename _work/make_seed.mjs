/* Generate migrations/0002_seed.sql from the storefront menu.
 *
 * The storefront file stays the single source of truth for the initial menu.
 * Later menu edits happen in D1 through the staff console, so this script is
 * only for the one-time seed (and for rebuilding a fresh review database).
 *
 * Usage: node _work/make_seed.mjs
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "assets", "js", "menu.js");
const OUT = path.join(ROOT, "migrations", "0002_seed.sql");

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(SOURCE, "utf8"), sandbox, { filename: "menu.js" });

const MENU = sandbox.window.MISO_MENU;
const SIGNATURES = sandbox.window.MISO_SIGNATURES;

if (!Array.isArray(MENU) || !Array.isArray(SIGNATURES)) {
  throw new Error("menu.js did not expose MISO_MENU / MISO_SIGNATURES");
}

function sqlStr(value) {
  if (value === null || value === undefined) return "NULL";
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function slug(text) {
  return String(text)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const lines = [];
lines.push("-- Generated by _work/make_seed.mjs from assets/js/menu.js.");
lines.push("-- Do not edit by hand; change the storefront menu and regenerate instead.");
lines.push("");

let groupCount = 0;
let itemCount = 0;
const itemIds = new Set();
const groupIds = new Set();

MENU.forEach((cat, ci) => {
  lines.push(
    "INSERT OR IGNORE INTO categories (id, name, kicker, blurb, image, sort_order, hidden) VALUES (" +
      [
        sqlStr(cat.id),
        sqlStr(cat.name),
        sqlStr(cat.kicker || ""),
        sqlStr(cat.blurb || ""),
        sqlStr(cat.image),
        ci,
        0
      ].join(", ") +
      ");"
  );
});

MENU.forEach((cat, ci) => {
  (cat.groups || []).forEach((group, gi) => {
    const base = `${cat.id}/${slug(group.name)}`;
    let id = base;
    let n = 2;
    while (groupIds.has(id)) id = `${base}-${n++}`;
    groupIds.add(id);
    groupCount += 1;

    lines.push("");
    lines.push(
      "INSERT OR IGNORE INTO menu_groups (id, category_id, name, sort_order) VALUES (" +
        [sqlStr(id), sqlStr(cat.id), sqlStr(group.name), gi].join(", ") +
        ");"
    );

    (group.items || []).forEach((item, ii) => {
      if (itemIds.has(item.id)) throw new Error(`Duplicate item id: ${item.id}`);
      itemIds.add(item.id);
      itemCount += 1;

      lines.push(
        "INSERT OR IGNORE INTO items (id, group_id, name, description, price, tags, sort_order, hidden) VALUES (" +
          [
            sqlStr(item.id),
            sqlStr(id),
            sqlStr(item.name),
            sqlStr(item.desc || ""),
            item.price === null || item.price === undefined ? "NULL" : Number(item.price),
            sqlStr(JSON.stringify(item.tags || [])),
            ii,
            0
          ].join(", ") +
          ");"
      );
    });
  });
});

lines.push("");
SIGNATURES.forEach((sig, index) => {
  if (!itemIds.has(sig.itemId)) throw new Error(`Signature item missing: ${sig.itemId}`);
  lines.push(
    "INSERT OR IGNORE INTO signatures (slot, item_id, image, label, note) VALUES (" +
      [index + 1, sqlStr(sig.itemId), sqlStr(sig.image), sqlStr(sig.label), sqlStr(sig.note)].join(", ") +
      ");"
  );
});

lines.push("");
lines.push("INSERT OR IGNORE INTO meta (key, value) VALUES ('menu_version', '1');");
lines.push("");

const expected = { categories: 6, groups: 25, items: 114, signatures: 4 };
const actual = {
  categories: MENU.length,
  groups: groupCount,
  items: itemCount,
  signatures: SIGNATURES.length
};
for (const key of Object.keys(expected)) {
  if (actual[key] !== expected[key]) {
    throw new Error(`Expected ${expected[key]} ${key}, found ${actual[key]}. Update the generator deliberately.`);
  }
}

const phadThai = MENU.flatMap((c) => c.groups).flatMap((g) => g.items).find((i) => i.id === "phad-thai-prawns");
const mixMeat = MENU.flatMap((c) => c.groups).flatMap((g) => g.items).find((i) => i.id === "mix-meat-fried-rice");
if (!phadThai || phadThai.price !== null) throw new Error("Phad Thai with Prawns must stay price-on-request");
if (!mixMeat || mixMeat.price !== 35000) throw new Error("Mix Meat Fried Rice must stay 35000");

fs.writeFileSync(OUT, lines.join("\n"), "utf8");
console.log(
  `Wrote ${path.relative(ROOT, OUT)} — ${actual.categories} categories, ${actual.groups} groups, ` +
    `${actual.items} items, ${actual.signatures} signatures.`
);
